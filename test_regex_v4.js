// Самый простой и надежный способ для IPv6 (захватывает группы 16-битных блоков и двоеточия)
const ipv6Regex = /\b(?:[a-fA-F0-9]{1,4}|(?::(?::[a-fA-F0-9]{1,4}){1,7}|:(?::[a-fA-F0-9]{1,4}){0,7})|(?::[a-fA-F0-9]{1,4}){1,7}:|(?::[a-fA-F0-9]{1,4}){1,7}::|(?::[a-fA-F0-9]{1,4}){1,7}(?::[a-fA-F0-9]{1,4}){1,7})(?::[a-fA-F0-9]{1,4}|:)*\b/g;

// Еще вариант:
const ipv6Regex2 = /(([0-9a-fA-F]{1,4}:){1,7}|:)(:[0-9a-fA-F]{1,4}){1,7}|([0-9a-fA-F]{1,4}:){1,7}:|::/g;

