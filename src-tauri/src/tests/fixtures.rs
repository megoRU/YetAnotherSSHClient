//! Фикстуры тестов: значения, которые не должны выглядеть секретами.
//!
//! Сканеры секретов ищут в исходниках два вида строк:
//!
//! * заголовки PEM вида «пять тире, BEGIN, метка, пять тире» — и считают их
//!   приватным ключом, даже когда тело состоит из заглушки;
//! * пары «имя=значение», похожие на учётные данные (`password=…`, `token: …`).
//!
//! Тестам нужен признак формата, а не ключ, поэтому и то и другое собирается
//! здесь, во время выполнения теста.
//!
//! **Правило:** тест, которому нужен заголовок PEM или значение «пароля», берёт
//! их отсюда. Собирать такие строки в самих тестах нельзя — они тут же попадут
//! в отчёт сканера.
//!
//! Честные ключи для проверок разбора не хранятся вовсе: они создаются при
//! запуске теста из системной энтропии через `rsa`/`ed25519` (см. `tests/keys.rs`).

/// Тире вокруг метки PEM.
///
/// Отдельная константа нужна для одной причины: заголовок приватного ключа не
/// должен встречаться в исходниках целиком — по нему сканер опознаёт ключ.
const DASHES: &str = "-----";

/// Открывающая строка PEM: пять тире, `BEGIN`, метка, пять тире.
///
/// Границы собираются, а не пишутся литералом: полная строка-заголовок
/// приватного ключа в исходнике — это ровно то, что ищет сканер секретов.
pub fn pem_begin(label: &str) -> String {
    format!("{DASHES}BEGIN {label}{DASHES}")
}

/// Закрывающая строка PEM: пять тире, `END`, метка, пять тире.
pub fn pem_end(label: &str) -> String {
    format!("{DASHES}END {label}{DASHES}")
}

/// Тело PEM-заглушки.
///
/// Это base64 от ascii-строки `not-a-key`, а не сам текст: base64 должен быть
/// корректным, иначе проверки падали бы по другой причине — «не base64» вместо
/// «не DER». Содержимое при этом осмысленное и заведомо не ключевое.
pub const PEM_BODY_PLACEHOLDER: &str = "bm90LWEta2V5";

/// Контейнер PEM с указанной меткой и заглушкой вместо содержимого.
///
/// Годится для проверок «формат опознаётся / не опознаётся» и для входа в
/// маскировщик логов. Для проверок разбора нужен настоящий ключ — его создаёт
/// сам тест.
pub fn pem_envelope(label: &str) -> String {
    pem_envelope_with_body(label, PEM_BODY_PLACEHOLDER)
}

/// Контейнер PEM с произвольным телом — для проверок «метка верная, а содержимое
/// мусорное».
pub fn pem_envelope_with_body(label: &str, body: &str) -> String {
    format!("{}\n{}\n{}", pem_begin(label), body, pem_end(label))
}

/// Обрезанный контейнер: открывающая строка и тело, без закрывающей.
///
/// Отдельная фикстура, потому что это другая проверка: заголовок есть, а
/// `END`-метки нет, и код обязан такое отвергнуть.
pub fn pem_truncated(label: &str) -> String {
    format!("{}\n{}", pem_begin(label), PEM_BODY_PLACEHOLDER)
}

