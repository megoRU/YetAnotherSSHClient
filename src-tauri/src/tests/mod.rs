//! Тесты приложения.
//!
//! Все тесты лежат в одной папке — рядом с модулем, который они проверяют, но
//! вне его исходника. Подключаются из самих модулей:
//!
//! ```ignore
//! #[cfg(test)]
//! #[path = "tests/keys.rs"]
//! mod tests;
//! ```
//!
//! Такое расположение удобно тем, что тесты видят приватные детали модуля
//! (иначе их пришлось бы делать публичными), но при этом не занимают место в
//! рабочем коде: файл модуля заканчивается двумя строками объявления.
//!
//! Общие помощники лежат здесь же: например, [`ssh_server`] — встроенный SSH-сервер
//! на базе `russh`, на котором проверяется клиентский код без внешнего `sshd`,
//! и [`fixtures`] — значения, которые не должны попасть под сканер секретов.

